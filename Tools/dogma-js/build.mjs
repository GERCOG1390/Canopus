// Bundles the desktop's dogma engine for the iOS app (JavaScriptCore). Needs canopus-desktop checked out
// next to this repo (../canopus-desktop) with its node_modules installed. Run: node Tools/dogma-js/build.mjs
import { execSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const desktop = resolve(here, '../../../canopus-desktop')
const dogmaDir = join(desktop, 'src/main/dogma')
const esbuild = createRequire(join(desktop, 'package.json'))('esbuild')
const rev = execSync('/usr/bin/git rev-parse --short HEAD', { cwd: desktop }).toString().trim()

// The desktop modules reach the SDE and the Electron-bound index through these two imports.
const shims = {
  name: 'ios-shims',
  setup(b) {
    b.onResolve({ filter: /^\.\.\/sde$/ }, (a) => (a.resolveDir === dogmaDir ? { path: join(here, 'shim-sde.ts') } : undefined))
    b.onResolve({ filter: /^\.\/index$/ }, (a) => (a.resolveDir === dogmaDir ? { path: join(here, 'shim-index.ts') } : undefined))
  }
}

await esbuild.build({
  entryPoints: [join(here, 'entry.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  platform: 'neutral',
  plugins: [shims],
  outfile: join(here, '../../Packages/EVEStaticData/Sources/EVEStaticData/Resources/canopus-dogma.js'),
  banner: { js: `// Generated by Tools/dogma-js/build.mjs from canopus-desktop ${rev}. Do not edit.` }
})
